 Сортировка — это упорядочивание данных (например, по возрастанию или убыванию). Она используется:

для удобного поиска (например, бинарный поиск работает только на отсортированных массивах);

для сравнения, группировки, фильтрации;

в алгоритмах: обработки текстов, чисел, таблиц, баз данных.


    Пузырьковая сортировка (Bubble Sort)
📖 Суть:
Алгоритм многократно проходит по массиву и пузырьком "выталкивает" большие элементы вправо, сравнивая попарно соседние элементы и меняя их местами, если порядок нарушен.

📌 Для чего:
Прост для понимания и обучения.

Хорош для маленьких массивов (до 10–20 элементов).

Неэффективен для больших данных.



Шейкерная сортировка (Shaker Sort, или "коктейльная")
📖 Суть:
Это улучшение пузырьковой сортировки. Сортировка идёт в обе стороны:

Вперёд — как в пузырьковой сортировке.

Назад — чтобы маленькие элементы быстрее сдвигались влево.

📌 Для чего:
Эффективнее пузырьковой на почти отсортированных данных.

Немного быстрее при плохом расположении элементов.



    Алгоритмическая сложность описывает, как быстро растёт время работы алгоритма при увеличении размера входных данных (n).
 Как определяется сложность:
Смотрим, сколько раз алгоритм проходит по данным (n, n², log n...).

Считаем основные операции (сравнение, обмен, присваивание).

Оцениваем:

Худший случай (O) — при самом неудачном порядке.

Лучший случай (Ω) — когда всё уже отсортировано.
 
